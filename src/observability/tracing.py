"""
Arize Phoenix & OpenTelemetry Native Auto-Instrumentation & Telemetry
Business Case ID: BC-AAIE-HACK-06 (AC-07, AC-08, AC-09)

Core Principles:
- 100% authentic OpenTelemetry SDK spans produced via OpenInference LangChain auto-instrumentation.
- Eliminates hand-crafted spans and fake deterministic ID generators.
- Genuine 32-hex trace IDs and 16-hex span IDs generated by the OpenTelemetry SDK.
- Non-estimated token counts directly captured from ChatGoogleGenerativeAI metadata.
- Native parent/child nesting across chains, nodes, tools, and LLM calls.
- Per-run parquet archive under traces/runs/ and latest at traces/phoenix_spans.parquet.
- Single unified @logged_tool(agent) decorator correlating tool calls with live Phoenix trace/span IDs.
"""

